-- Schema for the HelloFresh clone API. Written to run on both PostgreSQL (prod) and H2 in PostgreSQL mode (dev/test).

CREATE TABLE meal_kit (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug                 VARCHAR(80)   NOT NULL UNIQUE,
    title                VARCHAR(120)  NOT NULL,
    subtitle             VARCHAR(160)  NOT NULL,
    description          VARCHAR(1000) NOT NULL,
    image_url            VARCHAR(500)  NOT NULL,
    cooking_time_minutes INTEGER       NOT NULL CHECK (cooking_time_minutes > 0),
    calories             INTEGER       NOT NULL CHECK (calories > 0),
    price_per_serving    NUMERIC(6, 2) NOT NULL CHECK (price_per_serving > 0),
    sort_order           INTEGER       NOT NULL DEFAULT 0
);

CREATE TABLE meal_kit_tag (
    meal_kit_id BIGINT      NOT NULL REFERENCES meal_kit (id) ON DELETE CASCADE,
    tag         VARCHAR(40) NOT NULL,
    PRIMARY KEY (meal_kit_id, tag)
);

CREATE TABLE plan (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    people            INTEGER       NOT NULL CHECK (people > 0),
    meals_per_week    INTEGER       NOT NULL CHECK (meals_per_week > 0),
    price_per_serving NUMERIC(6, 2) NOT NULL CHECK (price_per_serving > 0),
    shipping_fee      NUMERIC(6, 2) NOT NULL CHECK (shipping_fee >= 0),
    CONSTRAINT uq_plan_people_meals UNIQUE (people, meals_per_week)
);

CREATE TABLE plan_request (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(80)              NOT NULL,
    email          VARCHAR(254)             NOT NULL,
    plan_id        BIGINT                   NOT NULL REFERENCES plan (id),
    meal_kit_id    BIGINT                   REFERENCES meal_kit (id),
    weekly_total   NUMERIC(8, 2)            NOT NULL,
    status         VARCHAR(20)              NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_plan_request_email ON plan_request (email);
